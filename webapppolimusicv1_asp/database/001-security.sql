SET XACT_ABORT ON;
IF OBJECT_ID('dbo.PM_CREDENTIAL','U') IS NULL
CREATE TABLE dbo.PM_CREDENTIAL(
  ID_USER int NOT NULL CONSTRAINT PK_PM_CREDENTIAL PRIMARY KEY,
  SALT varchar(32) NOT NULL,
  PASSWORD_HASH varchar(64) NOT NULL,
  ITERATIONS int NOT NULL,
  CONSTRAINT FK_PM_CREDENTIAL_USER FOREIGN KEY(ID_USER) REFERENCES dbo.TBL_USER(ID_USER)
);
IF OBJECT_ID('dbo.PM_LOGIN_LIMIT','U') IS NULL
CREATE TABLE dbo.PM_LOGIN_LIMIT(
  ATTEMPT_KEY varchar(64) NOT NULL CONSTRAINT PK_PM_LOGIN_LIMIT PRIMARY KEY,
  FAILURES int NOT NULL DEFAULT 0,
  WINDOW_START datetime NOT NULL DEFAULT GETUTCDATE()
);
IF OBJECT_ID('dbo.PM_AUTH_TICKET','U') IS NULL
CREATE TABLE dbo.PM_AUTH_TICKET(
  TOKEN varchar(64) NOT NULL CONSTRAINT PK_PM_AUTH_TICKET PRIMARY KEY,
  ID_USER int NOT NULL,
  EXPIRES_AT datetime NOT NULL,
  CONSTRAINT FK_PM_AUTH_TICKET_USER FOREIGN KEY(ID_USER) REFERENCES dbo.TBL_USER(ID_USER)
);
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE name='UX_PM_USERNAME' AND object_id=OBJECT_ID('dbo.TBL_USER'))
CREATE UNIQUE INDEX UX_PM_USERNAME ON dbo.TBL_USER(USERNAME);
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE name='UX_PM_EMAIL' AND object_id=OBJECT_ID('dbo.TBL_USER'))
CREATE UNIQUE INDEX UX_PM_EMAIL ON dbo.TBL_USER(EMAIL);

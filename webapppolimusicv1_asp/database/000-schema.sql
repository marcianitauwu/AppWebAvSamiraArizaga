-- Reference schema reconstructed from the existing BDD_PoliMusic database.
-- The originally mentioned BDD_PoliMusic.sql was not present in this checkout.
-- Use only to initialize an empty database; no existing table is dropped.
SET XACT_ABORT ON;
IF OBJECT_ID('dbo.TBL_USER','U') IS NULL
CREATE TABLE dbo.TBL_USER(
 ID_USER int IDENTITY(1,1) PRIMARY KEY,
 USERNAME varchar(50) NOT NULL,
 PASSWORD varchar(50) NOT NULL,
 EMAIL varchar(50) NOT NULL,
 BIRTHDAY datetime NULL,
 USER_PHOTO varchar(255) NULL,
 USER_TYPE int NOT NULL
);
IF OBJECT_ID('dbo.TBL_SONG','U') IS NULL
CREATE TABLE dbo.TBL_SONG(
 ID_SONG int IDENTITY(1,1) PRIMARY KEY,
 SONG_NAME varchar(50) NOT NULL,
 SONG_PATH varchar(255) NOT NULL,
 PLAYS int NULL DEFAULT 0
);
IF OBJECT_ID('dbo.TBL_ARTIST','U') IS NULL
CREATE TABLE dbo.TBL_ARTIST(
 ID_ARTIST int IDENTITY(1,1) PRIMARY KEY,
 ARTIST_NAME varchar(100) NOT NULL,
 ARTIST_LASTNAME varchar(100) NULL,
 ARTIST_IMAGE varchar(255) NULL
);
IF OBJECT_ID('dbo.TBL_ALBUM','U') IS NULL
CREATE TABLE dbo.TBL_ALBUM(
 ID_ALBUM int IDENTITY(1,1) PRIMARY KEY,
 TITLE_ALBUM varchar(50) NOT NULL,
 RELEASE_YEAR int NULL,
 ALBUM_IMAGE_PATH varchar(255) NULL
);
IF OBJECT_ID('dbo.TBL_PLAYLIST','U') IS NULL
CREATE TABLE dbo.TBL_PLAYLIST(
 ID_PLAYLIST int IDENTITY(1,1) PRIMARY KEY,
 ID_USER int NOT NULL REFERENCES dbo.TBL_USER(ID_USER),
 TITLE varchar(50) NOT NULL,
 CREATION_DATE datetime NOT NULL DEFAULT GETDATE(),
 TYPE int NOT NULL,
 PHOTO varchar(255) NULL
);
IF OBJECT_ID('dbo.TBL_PLAYER','U') IS NULL
CREATE TABLE dbo.TBL_PLAYER(
 ID_SONG int NOT NULL REFERENCES dbo.TBL_SONG(ID_SONG),
 ID_ARTIST int NOT NULL REFERENCES dbo.TBL_ARTIST(ID_ARTIST),
 PRIMARY KEY(ID_SONG,ID_ARTIST)
);
IF OBJECT_ID('dbo.TBL_TRACKLIST','U') IS NULL
CREATE TABLE dbo.TBL_TRACKLIST(
 ID_ALBUM int NOT NULL REFERENCES dbo.TBL_ALBUM(ID_ALBUM),
 ID_SONG int NOT NULL REFERENCES dbo.TBL_SONG(ID_SONG),
 PRIMARY KEY(ID_ALBUM,ID_SONG)
);
IF OBJECT_ID('dbo.TBL_PLAYLIST_SONG','U') IS NULL
CREATE TABLE dbo.TBL_PLAYLIST_SONG(
 ID_PLAYLIST int NOT NULL REFERENCES dbo.TBL_PLAYLIST(ID_PLAYLIST),
 ID_SONG int NOT NULL REFERENCES dbo.TBL_SONG(ID_SONG),
 PRIMARY KEY(ID_PLAYLIST,ID_SONG)
);
IF OBJECT_ID('dbo.TBL_CATALOG','U') IS NULL
CREATE TABLE dbo.TBL_CATALOG(
 ID_CATALOG int IDENTITY(1,1) PRIMARY KEY,
 COD_CATALOG_PARENT varchar(8) NULL,
 COD_CATALOG varchar(8) NULL,
 VALUE varchar(255) NOT NULL
);
